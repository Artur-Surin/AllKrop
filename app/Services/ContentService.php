    public static function getServiceBySlug(string $slug): ?array
    {
        foreach (static::serviceGroups() as $group) {
            foreach ($group['items'] as $item) {
                if ($item['slug'] === $slug) {
                    $item['group_category'] = $group['category'];

                    return $item;
                }
            }
        }

        return null;
    }

